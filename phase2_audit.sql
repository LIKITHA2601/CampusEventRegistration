-- ================================================================
-- CAMPUS EVENT SYSTEM - PHASE 2 AUDIT LOG (CORRECTED)
-- Run once in SQL Developer while connected as CAMPUS.
-- Adds audit objects only; does not recreate Phase 1 tables.
-- Based on Phase 1 schema:
-- REGISTRATIONS(registration_id, student_id, event_id, status)
-- TICKETS(ticket_id, registration_id, payment_status, ticket_price)
-- ================================================================

-- If this script was partially run before, check USER_OBJECTS first.
-- Do not drop existing audit objects automatically.

-- Idempotent table creation: safe to rerun if the audit table already exists.
BEGIN
    EXECUTE IMMEDIATE q'~CREATE TABLE campus_audit_log (
        audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        table_name     VARCHAR2(30) NOT NULL,
        operation_type VARCHAR2(10) NOT NULL,
        record_key     VARCHAR2(200),
        old_value      VARCHAR2(1000),
        new_value      VARCHAR2(1000),
        changed_by     VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV','SESSION_USER') NOT NULL,
        changed_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
    )~';
    DBMS_OUTPUT.PUT_LINE('CAMPUS_AUDIT_LOG created.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('CAMPUS_AUDIT_LOG already exists; keeping existing rows.');
        ELSE
            RAISE;
        END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_audit_reg_status
AFTER INSERT OR UPDATE OR DELETE ON registrations
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO campus_audit_log
            (table_name, operation_type, record_key, old_value, new_value)
        VALUES
            ('REGISTRATIONS', 'INSERT', TO_CHAR(:NEW.registration_id),
             NULL,
             'student=' || TO_CHAR(:NEW.student_id) ||
             '; event=' || TO_CHAR(:NEW.event_id) ||
             '; status=' || :NEW.status);
    ELSIF UPDATING THEN
        INSERT INTO campus_audit_log
            (table_name, operation_type, record_key, old_value, new_value)
        VALUES
            ('REGISTRATIONS', 'UPDATE', TO_CHAR(:NEW.registration_id),
             'status=' || :OLD.status,
             'status=' || :NEW.status);
    ELSIF DELETING THEN
        INSERT INTO campus_audit_log
            (table_name, operation_type, record_key, old_value, new_value)
        VALUES
            ('REGISTRATIONS', 'DELETE', TO_CHAR(:OLD.registration_id),
             'student=' || TO_CHAR(:OLD.student_id) ||
             '; event=' || TO_CHAR(:OLD.event_id) ||
             '; status=' || :OLD.status,
             NULL);
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_audit_ticket_payment
AFTER INSERT OR UPDATE OR DELETE ON tickets
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO campus_audit_log
            (table_name, operation_type, record_key, old_value, new_value)
        VALUES
            ('TICKETS', 'INSERT', TO_CHAR(:NEW.ticket_id),
             NULL,
             'registration=' || TO_CHAR(:NEW.registration_id) ||
             '; status=' || :NEW.payment_status ||
             '; amount=' || TO_CHAR(:NEW.ticket_price));
    ELSIF UPDATING THEN
        INSERT INTO campus_audit_log
            (table_name, operation_type, record_key, old_value, new_value)
        VALUES
            ('TICKETS', 'UPDATE', TO_CHAR(:NEW.ticket_id),
             'payment_status=' || :OLD.payment_status,
             'payment_status=' || :NEW.payment_status);
    ELSIF DELETING THEN
        INSERT INTO campus_audit_log
            (table_name, operation_type, record_key, old_value, new_value)
        VALUES
            ('TICKETS', 'DELETE', TO_CHAR(:OLD.ticket_id),
             'registration=' || TO_CHAR(:OLD.registration_id) ||
             '; status=' || :OLD.payment_status,
             NULL);
    END IF;
END;
/

-- Verify audit objects. All three should be VALID.
SELECT object_name, object_type, status
FROM user_objects
WHERE object_name IN (
    'CAMPUS_AUDIT_LOG',
    'TRG_AUDIT_REG_STATUS',
    'TRG_AUDIT_TICKET_PAYMENT'
)
ORDER BY object_type, object_name;

